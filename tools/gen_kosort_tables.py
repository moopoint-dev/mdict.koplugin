#!/usr/bin/env python3
"""Generate the pinned Unicode tables behind the kosort-1 key order.

kosort-1 is defined against one Unicode version, recorded in the output, so
that the plugin (Lua) and any exporter (Python, tools/kosort.py) normalise
keys identically no matter which Unicode version their runtime ships. Run this
only when deliberately defining a new spec version (kosort-2, ...):

    python3 tools/gen_kosort_tables.py

writes mdict.koplugin/mdict/kosort1_tables.lua and tools/kosort1_tables.json.
"""
import json
import os
import sys
import unicodedata

SPEC = "kosort-1"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MAXCP = 0x110000

DROP_CATEGORIES = {"Zs", "Zl", "Zp", "Cc", "Cf", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po"}


def full_decomposition(cp):
    """Recursive compatibility decomposition (NFKD of one code point), or None."""
    ch = chr(cp)
    if 0xAC00 <= cp <= 0xD7A3:
        return None  # Hangul syllables are decomposed algorithmically
    d = unicodedata.normalize("NFKD", ch)
    if d == ch:
        return None
    return [ord(c) for c in d]


def main():
    decomp, ccc, comp, inert_breaks = {}, {}, {}, set()
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        if unicodedata.category(ch) == "Cn":
            continue
        c = unicodedata.combining(ch)
        if c:
            ccc[cp] = c
        d = full_decomposition(cp)
        if d:
            decomp[cp] = d
    # canonical compositions: primary composites with a two-character canonical decomposition
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF or (0xAC00 <= cp <= 0xD7A3):
            continue
        ch = chr(cp)
        raw = unicodedata.decomposition(ch)
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) != 2:
            continue
        # excluded from composition if NFC does not recompose it
        if unicodedata.normalize("NFC", unicodedata.normalize("NFD", ch)) != ch:
            continue
        if unicodedata.combining(chr(parts[0])):
            continue  # non-starter decompositions never compose
        comp.setdefault(parts[0], {})[parts[1]] = cp
    seconds = sorted({b for m in comp.values() for b in m})
    # characters that can change under NFKC on their own or by composing with a neighbour
    for cp in list(decomp) + list(ccc) + seconds:
        inert_breaks.add(cp)
    for cp in range(0x1100, 0x1200):  # Hangul jamo compose algorithmically
        inert_breaks.add(cp)
    lower, drop = {}, []
    for cp in range(MAXCP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        cat = unicodedata.category(ch)
        if cat == "Cn":
            continue
        lo = ch.lower()
        if lo != ch:
            lower[cp] = [ord(c) for c in lo]
        if cat in DROP_CATEGORIES:
            drop.append(cp)

    def ranges(cps):
        out, start, prev = [], None, None
        for cp in sorted(cps):
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                out.append((start, prev))
                start = prev = cp
        if start is not None:
            out.append((start, prev))
        return out

    data = {
        "spec": SPEC,
        "unicode": unicodedata.unidata_version,
        "decomp": {str(k): v for k, v in sorted(decomp.items())},
        "ccc": {str(k): v for k, v in sorted(ccc.items())},
        "comp": {str(a): {str(b): c for b, c in sorted(m.items())} for a, m in sorted(comp.items())},
        "lower": {str(k): v for k, v in sorted(lower.items())},
        "drop": ranges(drop),
        "changes": ranges(inert_breaks),
    }
    with open(os.path.join(HERE, "kosort1_tables.json"), "w") as f:
        json.dump(data, f, separators=(",", ":"))

    def lua_list(v):
        return "{" + ",".join(str(x) for x in v) + "}"

    lines = [
        "-- Generated by tools/gen_kosort_tables.py; do not edit.",
        "-- Unicode %s tables for the %s key order (see mdict/kosort.lua)." % (unicodedata.unidata_version, SPEC),
        "local D,C,K,L={},{},{},{}",
    ]
    for k, v in sorted(decomp.items()):
        lines.append("D[%d]=%s" % (k, lua_list(v)))
    for k, v in sorted(ccc.items()):
        lines.append("C[%d]=%d" % (k, v))
    for a, m in sorted(comp.items()):
        lines.append("K[%d]={%s}" % (a, ",".join("[%d]=%d" % (b, c) for b, c in sorted(m.items()))))
    for k, v in sorted(lower.items()):
        lines.append("L[%d]=%s" % (k, lua_list(v)))
    lines.append("return {spec=%r,unicode=%r,decomp=D,ccc=C,comp=K,lower=L," % (SPEC, unicodedata.unidata_version))
    lines.append("drop={" + ",".join("{%d,%d}" % r for r in ranges(drop)) + "},")
    lines.append("changes={" + ",".join("{%d,%d}" % r for r in ranges(inert_breaks)) + "}}")
    src = "\n".join(lines).replace("'", '"') + "\n"
    with open(os.path.join(ROOT, "mdict.koplugin", "mdict", "kosort1_tables.lua"), "w") as f:
        f.write(src)
    print("unicode", unicodedata.unidata_version, "decomp", len(decomp), "ccc", len(ccc),
          "comp", sum(len(m) for m in comp.values()), "lower", len(lower), "drop ranges", len(ranges(drop)),
          file=sys.stderr)


if __name__ == "__main__":
    main()
